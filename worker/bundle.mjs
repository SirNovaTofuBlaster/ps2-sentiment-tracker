// Makes worker/spindle-crowd.bundle.js: index.js and lib.js as ONE file, for pasting into Cloudflare's dashboard editor
// (which takes a single file). Run from the repository root:  node worker/bundle.mjs
// tests/worker_check.mjs fails when the saved bundle is out of date.
import { readFileSync, writeFileSync } from 'node:fs';

export function build() {
    const lib = readFileSync(new URL('./lib.js', import.meta.url), 'utf8').replace(/^export /gm, '');
    const index = readFileSync(new URL('./index.js', import.meta.url), 'utf8')
        .replace(/^import \{[^}]*\} from '\.\/lib\.js';\n/m, '');
    return `// GENERATED by worker/bundle.mjs from lib.js and index.js: change those, not this file.\n${lib}\n${index}`;
}

if (process.argv[1] && import.meta.url === new URL(process.argv[1], 'file://').href) {
    writeFileSync(new URL('./spindle-crowd.bundle.js', import.meta.url), build());
    console.log('wrote worker/spindle-crowd.bundle.js');
}
